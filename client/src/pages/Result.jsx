import { useEffect, useState } from "react";
import { motion } from "framer-motion";
import { useNavigate } from "react-router-dom";

export default function Result() {
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [openCard, setOpenCard] = useState(null);
  const navigate = useNavigate();

  useEffect(() => {
    const fetchResult = async () => {
      try {
        setLoading(true);

        const answers =
          JSON.parse(localStorage.getItem("answers")) || [];

        const response = await fetch(
          "http://localhost:5000/api/ai/analyze",
          {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
            },
            body: JSON.stringify({ answers }),
          }
        );

        const data = await response.json();

        if (!response.ok) {
          throw new Error(data.error || "Server Error");
        }

        setResult(data);
      } catch (err) {
        console.error(err);
        setError("Something went wrong while fetching AI result");
      } finally {
        setLoading(false);
      }
    };

    fetchResult();
  }, []);

  // LOADING SCREEN
  if (loading) {
    return (
      <div className="min-h-screen flex flex-col items-center justify-center bg-black text-white px-6">
        <div className="w-24 h-24 border-4 border-purple-500 border-t-transparent rounded-full animate-spin"></div>

        <h1 className="text-4xl font-bold mt-8 bg-gradient-to-r from-purple-400 to-cyan-400 bg-clip-text text-transparent">
          Aspira is analyzing your future...
        </h1>

        <p className="text-gray-400 mt-4 text-lg">
          Hang-on while Aspira is crafting your personalized career roadmap 🚀
        </p>
      </div>
    );
  }

  // ERROR SCREEN
  if (error) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-black text-white">
        <h1 className="text-2xl text-red-400">{error}</h1>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-black text-white px-6 py-12">

      {/* HEADER */}
      <motion.div
        initial={{ opacity: 0, y: -40 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.7 }}
        className="text-center mb-14"
      >
        <h1 className="text-6xl font-extrabold bg-gradient-to-r from-purple-400 via-pink-500 to-cyan-400 bg-clip-text text-transparent">
          Your Aspira Career Analysis
        </h1>

        <p className="text-gray-400 mt-5 text-xl">
          Personalized technical career roadmap generated by Aspira
        </p>
      </motion.div>

      {/* CAREER CARDS */}
      <div className="grid md:grid-cols-3 gap-8">

        {result?.careers?.map((career, index) => (
          <motion.div
            key={index}
            initial={{ opacity: 0, y: 40 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.6, delay: index * 0.2 }}
            className="backdrop-blur-xl bg-white/10 border border-white/20 rounded-3xl p-8 hover:scale-105 hover:shadow-2xl hover:shadow-purple-500/30 transition-all duration-500"
          >

            {/* TITLE */}
            <h2 className="text-3xl font-bold text-purple-300 mb-4">
              {career.role}
            </h2>

            {/* DESCRIPTION */}
<p className="text-gray-300 leading-7 line-clamp-6">
  About: {career.description || "No description available"}
</p>

{/* SALARY SECTION */}
<div style={{ marginTop: "25px" }}>
  <h3
    style={{
      fontSize: "24px",
      fontWeight: "bold",
      marginBottom: "15px",
      color: "#4ade80",
    }}
  >
    💰 Salary Range
  </h3>

  <div
    style={{
      display: "grid",
      gridTemplateColumns: "repeat(auto-fit, minmax(220px, 1fr))",
      gap: "15px",
    }}
  >

    {/* Beginner */}
    <div
      style={{
        background: "linear-gradient(135deg, #1e293b, #0f172a)",
        padding: "18px",
        borderRadius: "16px",
        border: "1px solid rgba(255,255,255,0.1)",
        boxShadow: "0 4px 15px rgba(0,0,0,0.3)",
      }}
    >
      <p
        style={{
          color: "#94a3b8",
          fontSize: "14px",
          marginBottom: "8px",
        }}
      >
        Beginner
      </p>

      <h2
        style={{
          color: "#ffffff",
          fontSize: "24px",
          fontWeight: "bold",
        }}
      >
        {career.salary?.beginner || "N/A"}
      </h2>
    </div>

    {/* Intermediate */}
    <div
      style={{
        background: "linear-gradient(135deg, #1e293b, #0f172a)",
        padding: "18px",
        borderRadius: "16px",
        border: "1px solid rgba(255,255,255,0.1)",
        boxShadow: "0 4px 15px rgba(0,0,0,0.3)",
      }}
    >
      <p
        style={{
          color: "#94a3b8",
          fontSize: "14px",
          marginBottom: "8px",
        }}
      >
        Intermediate
      </p>

      <h2
        style={{
          color: "#38bdf8",
          fontSize: "24px",
          fontWeight: "bold",
        }}
      >
        {career.salary?.intermediate || "N/A"}
      </h2>
    </div>

    {/* Experienced */}
    <div
      style={{
        background: "linear-gradient(135deg, #1e293b, #0f172a)",
        padding: "18px",
        borderRadius: "16px",
        border: "1px solid rgba(255,255,255,0.1)",
        boxShadow: "0 4px 15px rgba(0,0,0,0.3)",
      }}
    >
      <p
        style={{
          color: "#94a3b8",
          fontSize: "14px",
          marginBottom: "8px",
        }}
      >
        Experienced
      </p>

      <h2
        style={{
          color: "#facc15",
          fontSize: "24px",
          fontWeight: "bold",
        }}
      >
        {career.salary?.experienced || "N/A"}
      </h2>
    </div>

  </div>
</div>

            {/* SKILLS */}
            <div className="mt-8">
              <h3 className="text-2xl font-bold mb-4">
                🧠 Skills Required
              </h3>

              <div className="flex flex-wrap gap-3">
                {career.skills?.map((skill, i) => (
                  <span
                    key={i}
                    className="px-4 py-2 rounded-full bg-purple-600/30 border border-purple-500 text-sm"
                  >
                    {skill}
                  </span>
                ))}
              </div>
            </div>

            {/* TECHNOLOGIES */}
            <div className="mt-8">
              <h3 className="text-2xl font-bold mb-4">
                🤖 Technologies
              </h3>

              <div className="flex flex-wrap gap-3">
                {career.technologies?.map((tech, i) => (
                  <span
                    key={i}
                    className="px-4 py-2 rounded-full bg-cyan-500/20 border border-cyan-400 text-sm"
                  >
                    {tech}
                  </span>
                ))}
              </div>
            </div>

            {/* EXPAND BUTTON */}
            <motion.button
              whileHover={{ scale: 1.05 }}
              whileTap={{ scale: 0.95 }}
              onClick={() =>
                setOpenCard(
                  openCard === index ? null : index
                )
              }
              className="mt-8 w-full py-4 rounded-2xl bg-gradient-to-r from-purple-600 to-pink-600 font-bold text-lg hover:shadow-xl hover:shadow-purple-500/40 transition-all"
            >
              {openCard === index
                ? "Hide Details"
                : "View Full Roadmap"}
            </motion.button>

            {/* EXPANDED SECTION */}
            {openCard === index && (
              <motion.div
                initial={{ opacity: 0, height: 0 }}
                animate={{ opacity: 1, height: "auto" }}
                transition={{ duration: 0.5 }}
                className="mt-8"
              >

                {/* ROADMAP */}
                <div className="mb-10">
                  <h3 className="text-2xl font-bold mb-6 text-cyan-300">
                    🗺️ Step-by-Step Roadmap
                  </h3>

                  <div className="space-y-5">
                    {career.roadmap?.map((step, i) => (
                      <div
                        key={i}
                        className="flex gap-4 items-start"
                      >
                        <div className="w-10 h-10 rounded-full bg-purple-600 flex items-center justify-center font-bold">
                          {i + 1}
                        </div>

                        <div className="bg-white/5 border border-white/10 rounded-2xl p-4 flex-1">
                          {step}
                        </div>
                      </div>
                    ))}
                  </div>
                </div>

                <div className="bg-white/5 border border-white/10 rounded-2xl p-5 text-gray-300">
                    <h3 className="text-2xl font-bold mb-6 text-cyan-300">
                        🗺️ DAILY DISCIPLINE ROUTINE
                    </h3>

  
  {/* DAILY ROUTINE TEXT */}
  
  <div className="leading-8">
    {career.dailyRoutine}
  </div>

  {/* TAKE EXPERIENCE BUTTON (INSIDE SAME FIELD) */}
  <div className="mt-5 flex justify-end">
    <button
      onClick={() =>
        navigate("/experience", {
          state: { role: career.role }
        })
      }
      className="px-5 py-2 bg-gradient-to-r from-yellow-400 to-orange-500 text-black font-bold rounded-xl"
    >
      🚀 Take Experience
    </button>
  </div>

</div>

                {/* PROJECTS */}
                <div className="mb-10">
                  <h3 className="text-2xl font-bold mb-5 text-yellow-300">
                    Recommended Projects
                  </h3>

                  <div className="space-y-4">
                    {career.projects?.map((project, i) => (
                      <div
                        key={i}
                        className="bg-white/5 border border-white/10 rounded-2xl p-5"
                      >
                        🚀 {project}
                      </div>
                    ))}
                  </div>
                </div>

                {/* YOUTUBE */}
<div className="mb-10">
  <h3 className="text-2xl font-bold mb-5 text-red-300">
    ▶️ Best YouTube Resources
  </h3>

  <div className="flex flex-col gap-4">

    {career.youtube &&
      career.youtube.map((video, i) => (

        <a
          key={i}
          href={video.link || "#"}
          target="_blank"
          rel="noreferrer"
          className="bg-red-500/20 border border-red-400 px-5 py-4 rounded-2xl hover:bg-red-500/30 transition-all"
        >

          <div className="font-bold text-lg">
            ▶ {video.name || "YouTube Resource"}
          </div>

          <div className="text-sm text-gray-300 mt-1 break-all">
            {video.link}
          </div>

        </a>

      ))}

  </div>
</div>

                {/* INTERNSHIP */}
<div className="mb-8">
  <h3 className="text-2xl font-bold mb-4 text-green-300">
    🎓 Internship Guidance
  </h3>

  <div className="space-y-4">

    {Array.isArray(career.internship) ? (

      career.internship.map((item, i) => (

        <div
          key={i}
          className="bg-white/5 border border-white/10 rounded-2xl p-5"
        >
          🚀 {item}
        </div>

      ))

    ) : (

      <div className="bg-white/5 border border-white/10 rounded-2xl p-5 leading-8 text-gray-300">
        {career.internship}
      </div>

    )}

  </div>
</div>

             {/* TOP COUNTRIES FIX (IMPORTANT PART) */}
            <div className="mt-6">
              <h3 className="text-xl font-semibold mb-2">
                🌍 Top Hiring Companies
              </h3>

              {Array.isArray(career.topCompanies) &&
              career.topCompanies.length > 0 ? (
                career.topCompanies.map((c, i) => (
                  <div
                    key={i}
                    className="bg-black/40 p-3 rounded-lg mb-2"
                  >
                    <p>
                      <b>{c.company || "Unknown"}</b>
                    </p>
                    <p className="text-sm text-gray-400">
                      Demand: {c.demandLevel || "MEDIUM"}
                    </p>
                  </div>
                ))
              ) : (
                <p className="text-gray-400">
                  Country insights not available
                </p>
              )}
            </div>

            {/* FUTURE */}
            <div className="mt-4">
              <h3 className="text-lg font-semibold text-orange-300">
                Future Scope
              </h3>
              <p className="text-gray-300">
                {career.future || "No data"}
              </p>
            </div>


              </motion.div>
            )}

          </motion.div>
        ))}

      </div>
    </div>
  );
}